export function loadRecords(dir: string): Map<string, E2EResult> {
  const out = new Map<string, E2EResult>();
  if (!existsSync(dir)) return out;
  for (const f of readdirSync(dir).filter((x) => x.endsWith(".json"))) {
    try {
      const r = JSON.parse(readFileSync(join(dir, f), "utf8")) as E2EResult;
      if (r.agent) out.set(r.agent, r);
    } catch {}
  }
  return out;
}

const ctx = (c: AgentCapabilities) =>
  c.contextAt.map((x) => (x === "tool.after" ? "next tool result" : x.replace(".", " "))).join(", ");

export function renderMatrix(records: Map<string, E2EResult>): string {
  const lines = [
    "# Support matrix",
    "",
    "Generated by `bun run bench matrix` from each adapter's declared capabilities and the real-agent records in `docs/e2e/`. Do not edit by hand.",
    "",
    "**Verified** means a recorded real run of the agent, with Sieve installed through its own project-level config, reached the daemon with the event that follows a tool call (`bun run bench agent-e2e <agent> --run`). **Live** means the adapter is in daily use in real sessions, but no run is recorded. **Preview** means neither: the mapping was read from the sources named below and is covered by tests that replay that agent's payload shapes, but no real session has confirmed it.",
    "",
    "| Agent | Integration | Support | Real run | Mapping read from | Replaces tool output | Deny / ask | Notes reach the model at | Compaction | Smart reads |",
    "|---|---|---|---|---|---|---|---|---|---|",
  ];
  for (const r of ROWS) {
    const rec = records.get(r.agent);
    const support = rec?.passed ? "verified" : r.caps.support === "live" ? "live" : "preview";
    const run = rec
      ? `${rec.passed ? "pass" : "FAIL"} · ${rec.agentVersion || "version unknown"} · ${rec.at.slice(0, 10)}`
      : "none";
    lines.push(
      `| ${r.name} | ${r.integration} | ${support} | ${run} | ${r.source} | ${r.caps.replace} | ${r.caps.deny ? "deny" : "no deny"}${r.caps.ask ? " / ask" : ""} | ${ctx(r.caps)} | ${r.caps.compaction === "reliable" ? "detected" : "manual only"} | ${r.reads} |`,
    );
  }
  lines.push(
    "",
    "Not built: Qwen Code, VS Code Copilot, Windsurf, Cline/Roo, Kiro, Zed, Pi, Aider, Goose (slice 12).",
    "",
    "- *Replaces tool output*: `all` means Sieve can swap a large tool result for a receipt before the model reads it; `none` means output is archived and searchable, but the model still receives it in full (the agent offers no clean way to replace it; ADR 0008).",
    '- *Notes reach the model at*: where the agent lets Sieve add text (staleness notices, recall pointers, the state block). "next tool result" means the agent has no slot on prompts, so the note waits for the next tool result.',
    "",
  );
  return lines.join("\n");
}
